import { readFile, writeFile } from 'node:fs/promises';

const pdf = await readFile(new URL('../assets/FastAPI-Guide.pdf', import.meta.url));
if (pdf.subarray(0, 5).toString() !== '%PDF-') throw new Error('Expected a PDF guide');

// A classic script can load from file:// without fetching the PDF across opaque
// file origins. Keep this generated copy in sync whenever the guide changes.
const script = `// Generated by npm run prepare:downloads. Edit the PDF, then regenerate.
(() => {
  'use strict';
  const link = document.getElementById('fastapi-guide-download');
  if (!link) return;
  const bytes = Uint8Array.from(atob('${pdf.toString('base64')}'), (character) => character.charCodeAt(0));
  link.href = URL.createObjectURL(new Blob([bytes], { type: 'application/pdf' }));
})();
`;

await writeFile(new URL('../assets/FastAPI-Guide.download.js', import.meta.url), script);
console.log('Prepared the FastAPI PDF download for direct file previews.');
